/* ******************************** mul8mx8i ******************************* */

void
mul8mx8i (float *r, const float *m, const int *i)
{
  float d;
  for (int k = 0; k < 8; k++)
    {
      for (int j = 0; j < 8; j++)
        {
          d = 0.0f;
          for (int n = 0; n < 8; n++)
            {
              d += m[k * 8 + n] * (float)i[n * 8 + j];
            }
          r[k * 8 + j] = d;
        }
    }
}

/* ******************************* mul8fx8mt ******************************* */

void
mul8fx8mt (int *r, const float *f, const float *m)
{
  float d;
  for (int k = 0; k < 8; k++)
    {
      for (int j = 0; j < 8; j++)
        {
          d = 0;
          for (int n = 0; n < 8; n++)
            {
              d += f[k * 8 + n] * m[n * 8 + j];
            }
          r[k * 8 + j] = clampi (d + 128, 0, 255);
        }
    }
}

/* ********************************** idct ********************************* */

void
idct (int *output, const int *input)
{
  float tmp[64];

  if (input == NULL || output == NULL)
    return;

  mul8mx8i (tmp, dct_mt, input);
  mul8fx8mt (output, tmp, dct_m);
}